/**
 * Retorna os desafios de voz e som para um determinado anime.
 * Ordena automaticamente dando prioridade máxima às RISADAS (estilo OnePieceDle),
 * seguidas por ataques e bordões icônicos em japonês original.
 */
export function getVoiceChallengesForAnime(animeSlug: string): VoiceChallenge[] {
  const list = VOICE_CHALLENGES[animeSlug];
  if (list && list.length > 0) {
    // Ordena priorizando risadas no topo da lista
    return [...list].sort((a, b) => {
      if (a.category === 'risada' && b.category !== 'risada') return -1;
      if (b.category === 'risada' && a.category !== 'risada') return 1;
      return 0;
    });
  }

  // Fallback seguro caso algum anime ainda não tenha clipes cadastrados
  return [
    {
      id: `voice-fallback-${animeSlug}`,
      animeSlug,
      characterId: 'default',
      characterName: 'Personagem Misterioso',
      audioUrl: 'https://www.myinstants.com/media/sounds/bankai.mp3',
      category: 'risada',
      language: 'Japonês (Original)',
      volumeGain: 0.85,
      playbackSpeed: 1.0,
    },
  ];
}
