const animes = fs.readdirSync('src/data/animes').filter(f => fs.statSync('src/data/animes/' + f).isDirectory());

let totalUpdated = 0;

for (const anime of animes) {
  const p = `src/data/animes/${anime}/characters.json`;
  if (!fs.existsSync(p)) continue;
  const chars = JSON.parse(fs.readFileSync(p, 'utf-8'));
  let changed = false;

  for (const c of chars) {
    // 1. Direct canon fix
    if (CANON_HAIR_FIXES[c.id]) {
      if (c.hairColor !== CANON_HAIR_FIXES[c.id]) {
        c.hairColor = CANON_HAIR_FIXES[c.id];
        changed = true;
        totalUpdated++;
      }
    } else if (NORMALIZATION_MAP[c.hairColor]) {
      // 2. Normalization
      c.hairColor = NORMALIZATION_MAP[c.hairColor];
      changed = true;
      totalUpdated++;
    }
  }

  if (changed) {
    fs.writeFileSync(p, JSON.stringify(chars, null, 2), 'utf-8');
    console.log(`Updated hair colors in ${anime}!`);
  }
}

console.log(`Total hair colors fixed and standardized: ${totalUpdated}`);
